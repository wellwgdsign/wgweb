const flagImages = {
    'pt-BR': 'assets/img/flags/br.svg',
    'en-US': 'assets/img/flags/us.svg',
    'es-ES': 'assets/img/flags/es.svg'
};

const langNames = {
    'pt-BR': 'PT-BR',
    'en-US': 'EN-US',
    'es-ES': 'Espanol'
};

let currentLanguage = localStorage.getItem('mudesign_lang') || 'pt-BR';

function detectUserCountry() {
    const savedLang = localStorage.getItem('mudesign_lang');
    if (savedLang) {
        return savedLang;
    }
    
    const browserLang = navigator.language || navigator.userLanguage;
    
    if (browserLang.startsWith('pt')) {
        return 'pt-BR';
    } else if (browserLang.startsWith('es')) {
        return 'es-ES';
    } else {
        return 'en-US';
    }
}

function getNestedValue(obj, path) {
    return path.split('.').reduce((current, key) => current?.[key], obj);
}

function translatePage(lang) {
    const t = translations[lang];
    if (!t) return;
    
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        const value = getNestedValue(t, key);
        if (value) {
            const icon = el.querySelector('i');
            if (icon) {
                el.textContent = '';
                el.appendChild(icon);
                el.appendChild(document.createTextNode(' ' + value));
            } else {
                el.textContent = value;
            }
        }
    });
    
    document.documentElement.lang = lang === 'pt-BR' ? 'pt-br' : (lang === 'es-ES' ? 'es' : 'en');
}

function changeLanguage(lang) {
    currentLanguage = lang;
    localStorage.setItem('mudesign_lang', lang);
    
    const currentFlag = document.getElementById('currentFlag');
    const currentLangText = document.getElementById('currentLang');
    
    if (currentFlag) {
        currentFlag.src = flagImages[lang];
    }
    if (currentLangText) {
        currentLangText.textContent = langNames[lang];
    }
    
    translatePage(lang);
    
    const dropdown = document.getElementById('languageDropdown');
    if (dropdown) {
        dropdown.classList.remove('open');
    }
    
    showToast(lang === 'pt-BR' ? 'Idioma alterado para Portugues' : 
              lang === 'en-US' ? 'Language changed to English' : 
              'Idioma cambiado a Espanol', 'success');
}

function toggleLanguageDropdown() {
    const dropdown = document.getElementById('languageDropdown');
    if (dropdown) {
        dropdown.classList.toggle('open');
    }
}

document.addEventListener('click', (e) => {
    const selector = document.getElementById('languageSelector');
    const dropdown = document.getElementById('languageDropdown');
    
    if (selector && dropdown && !selector.contains(e.target)) {
        dropdown.classList.remove('open');
    }
});

document.addEventListener('DOMContentLoaded', () => {
    const detectedLang = detectUserCountry();
    currentLanguage = detectedLang;
    
    const currentFlag = document.getElementById('currentFlag');
    const currentLangText = document.getElementById('currentLang');
    
    if (currentFlag) {
        currentFlag.src = flagImages[detectedLang];
    }
    if (currentLangText) {
        currentLangText.textContent = langNames[detectedLang];
    }
    
    translatePage(detectedLang);
});
